/** Назва сторінки за адресою. Порожній рядок, якщо адреси немає в переліку. */
export const nameOf = (to: string, lang: 'uk' | 'en'): string => {
  const p = ALL.find((x) => x.to === to);
  return p ? p[lang] : '';
};
