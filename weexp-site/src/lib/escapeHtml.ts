/**
 * Екранування тексту клієнта для HTML, який ми збираємо рядками.
 *
 * Копій цієї функції в кодовій базі було шість, і всі шість екранували лише
 * `& < >`. У текстовому вузлі цього досить, і саме так вони й використовувались —
 * я перевірив кожну інтерполяцію, жодна не стоїть в атрибуті. Але шість копій —
 * це шість місць, де наступний `title="${esc(x)}"` відкриє дірку, і жодного
 * місця, де це можна виправити один раз.
 *
 * Тому одна функція, і вона екранує ще й лапки: у текстовому вузлі `&quot;`
 * малюється як звичайна лапка, тобто суворіший варіант нічого не псує, а в
 * атрибуті рятує. Дані сюди приходять від клієнта — назва компанії, нотатка
 * менеджера, коментар з анкети — і поїдуть у документ, який відкриє аудитор.
 */
export function escapeHtml(s: unknown): string {
  return String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
