/**
 * ПРАВИЛА ПЕРЕНОСУ: один рядок для підпису, жодного висячого слова в реченні.
 *
 * Тут стережеться механіка, а замір робить браузер (scripts/checkFit.mjs:
 * режими --wrap і --orphan). Розділення таке: скільки слів лишилось в
 * останньому рядку — питання до живої верстки на дев'яти ширинах, а те, чим це
 * лагодять, має бути на місці й не ламатись мовчки.
 */
import { describe, it, expect } from 'vitest';
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const SRC = join(__dirname, '..');
const css = readFileSync(join(SRC, 'system', 'system.css'), 'utf8');
const tsxFiles = readdirSync(join(SRC, 'system')).filter((f) => f.endsWith('.tsx'));

describe('перенос керований, а не випадковий', () => {
  it('заголовкам — balance, абзацам — pretty', () => {
    // Два різні завдання: заголовку потрібні рядки рівної довжини, абзацу —
    // повний останній рядок. Одне правило на обидва не працює.
    expect(css).toMatch(/:is\(h1, h2, h3, h4, \.sysx-display\)\s*\{[^}]*text-wrap:\s*balance/);
    expect(css).toMatch(/:is\(p, li[^)]*\)\s*\{[^}]*text-wrap:\s*pretty/);
  });

  it('ручний перенос у заголовку зникає на вузькому екрані', () => {
    /*
     * `<br>` у заголовку — рішення для широкого екрана. На 320px кожна
     * половина ламається ще раз, і під повним рядком лишається одне слово;
     * до того ж ручний перенос відбирає роботу в balance, який на цій ширині
     * розклав би заголовок рівно сам.
     */
    expect(css).toMatch(/@media \(max-width: 760px\) \{ \.br-wide \{ display: none; \} \}/);
  });

  it('прихований перенос не склеює два слова', () => {
    /*
     * САМЕ ТАК ЦЕ Й ЗЛАМАЛОСЬ. `<br>` був єдиним роздільником між «Більше
     * продажів» і «з того самого трафіку»; display: none прибрав його — і на
     * телефоні заголовок став «БІЛЬШЕ ПРОДАЖІВЗ ТОГО САМОГО ТРАФІКУ». Верстка
     * ціла, розмір правильний, жоден сторож не падає, а слово зрощене з
     * наступним. Тому перед умовним переносом стоїть явний пробіл: на
     * широкому екрані він згортається в кінці рядка й нічого не змінює.
     */
    const glued: string[] = [];
    for (const f of tsxFiles) {
      const code = readFileSync(join(SRC, 'system', f), 'utf8');
      for (const m of code.matchAll(/(.{0,12})<br className="br-wide"/g))
        if (!/\{' '\}$|\s$/.test(m[1])) glued.push(`${f}: …${m[1]}`);
    }
    expect(glued, `перед прихованим переносом немає пробілу: ${glued.join(' | ')}`).toEqual([]);
  });

  it('умовний перенос — єдиний вид ручного переносу в розмітці', () => {
    // Голий <br /> у заголовку поводиться на телефоні так само погано, як той,
    // що тут уже виправлений: правило має діяти на всі, а не на ті дев'ять.
    const bare: string[] = [];
    for (const f of tsxFiles) {
      const code = readFileSync(join(SRC, 'system', f), 'utf8');
      if (/<br\s*\/>/.test(code)) bare.push(f);
    }
    expect(bare, `ручний перенос без класу .br-wide: ${bare.join(', ')}`).toEqual([]);
  });
});
