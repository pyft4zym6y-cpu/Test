/**
 * Мікротипографіка (i18n/typo).
 *
 * Правило «не лишати в кінці рядка» — це не косметика: саме однолітерні
 * прийменники давали найдовші хвости в заголовках («продажів з / того самого»
 * замість «продажів / з того самого»), а розірване «19 / млн» читається як
 * два різні числа.
 *
 * Сторож тримає МЕЖІ правила. Склеїти забагато так само погано, як замало:
 * нерозривний пробіл між числом і довгим словом робить шматок рядка
 * нерозривним, і в тісній комірці його вже нема де перенести.
 */
import { describe, it, expect } from 'vitest';
import { typo } from '@/i18n';

const NB = ' ';

describe('мікротипографіка', () => {
  it('прийменник не лишається в кінці рядка', () => {
    expect(typo('Більше продажів з того самого трафіку'))
      .toBe(`Більше продажів з${NB}того самого трафіку`);
    expect(typo('що робити в якому порядку')).toBe(`що${NB}робити в${NB}якому порядку`);
  });

  it('працює і в англійському тексті', () => {
    expect(typo('more sales from the same traffic'))
      .toBe('more sales from the same traffic');       // службових слів зі списку немає
    expect(typo('a map of the leak')).toBe(`a${NB}map of${NB}the leak`);
  });

  it('НЕ склеює коротке слово, яке не є службовим', () => {
    /*
     * «Ми перебудовуємо» — теж два символи плюс довге слово, але склеїти їх
     * означає зробити нерозривним шматок у шістнадцять знаків, який у вузькій
     * картці вже нікуди не помістити.
     */
    expect(typo('Ми перебудовуємо онлайн-продажі')).toBe('Ми перебудовуємо онлайн-продажі');
  });

  it('число не відривається від одиниці', () => {
    expect(typo('≥19 млн ₴')).toBe(`≥19${NB}млн ₴`);
    expect(typo('6 ринків')).toBe('6 ринків');          // не одиниця — не склеюємо
  });

  it('НЕ склеює число з довгим словом', () => {
    /*
     * Саме так це й ламалось: «$2,900 за проєкт» ставало нерозривним на
     * «900 за» — і в тісній комірці рядок уже не мав де перенестись.
     */
    expect(typo('$2,900 проєкт')).toBe('$2,900 проєкт');
  });

  it('тире не починає рядок', () => {
    expect(typo('Крок 1 — аудит')).toBe(`Крок 1${NB}— аудит`);
  });

  it('нічого не додає і не втрачає, крім самих пробілів', () => {
    // Текст мусить лишитись тим самим текстом: змінюється ЛИШЕ вид пробілу.
    for (const s of ['Більше продажів з того самого трафіку', '≥19 млн ₴ на рік', 'a map of the leak'])
      expect(typo(s).replace(/ /g, ' ')).toBe(s);
  });
});
