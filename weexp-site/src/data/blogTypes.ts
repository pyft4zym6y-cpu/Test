/**
 * Блог: модель статті.
 *
 * Форма продиктована не смаком, а тим, як текст читають три різні «читачі», і
 * жоден із них не читає так, як людина в кріслі:
 *
 *  • ПОШУК бере заголовок, опис, структуру H2 і внутрішні посилання;
 *  • AI-ВИДАЧА (AEO/GEO) цитує КОРОТКУ ПРЯМУ ВІДПОВІДЬ на початку і FAQ —
 *    саме тому `answer` тут окреме поле, а не перший абзац ліда: абзац, який
 *    «і вступ, і відповідь», не є ні тим, ні тим;
 *  • ЛЮДИНА читає лід, підзаголовки й висновок, а середину гортає.
 *
 * Тому кожна стаття зобовʼязана мати: прямий відповідь до 60 слів, структуру з
 * H2-питань, FAQ і посилання на сторінки, про які вона говорить. Порожній FAQ
 * або стаття без посилань — не стилістична вада, а невиконана робота; за цим
 * стежить тест.
 *
 * Зберігання: один JSON на статтю в src/content/blog. Так тіла лонгридів не
 * потрапляють у спільний бандл (їх вантажить лише сторінка статті), а
 * scripts/prerender.mjs читає ті самі файли без дубля даних у другому форматі.
 */

/** Розділ блогу. Збігається зі структурою сайту, щоб теми не жили окремо. */
export type BlogCategory =
  | 'systems'      // вісім систем онлайн-продажів
  | 'commerce'     // економіка продажів, юніт-економіка, маржа
  | 'traffic'      // попит, канали, SEO, реклама
  | 'experience'   // сайт, конверсія, UX
  | 'operations'   // склад, доставка, повернення
  | 'data'         // аналітика, інтеграції, звітність
  | 'org'          // ролі, процеси, незалежність від власника
  | 'expansion'    // вихід на нові ринки й маркетплейси
  | 'method';      // як влаштований аудит і робота з нами

export type BlogSection = {
  /** H2 — краще питанням: так його бачить і людина, і AI-видача. */
  h: string;
  p?: string[];
  list?: string[];
  /** Нумерований список — для послідовностей, де порядок має значення. */
  steps?: string[];
  /** Виносна теза або застереження. */
  note?: string;
  /** Таблиця: перший рядок — заголовки. */
  table?: string[][];
};

export type BlogArticle = {
  slug: string;
  title: string;
  /** <title> у видачі, якщо він має бути коротшим за H1. */
  seoTitle?: string;
  /** meta description: 140–165 символів, інакше видача її обріже або перепише. */
  description: string;
  keywords: string[];
  category: BlogCategory;
  /**
   * Сторінки сайту, до яких стаття належить: на них зʼявиться блок блогу, і
   * на них же стаття мусить посилатись. Звʼязок двобічний — інакше блок
   * перетворюється на випадковий список «схожого».
   */
  pages: string[];
  published: string;
  updated?: string;
  readMin: number;
  /** Пряма відповідь до 60 слів — те, що цитує AI-видача. */
  answer: string;
  lead: string;
  sections: BlogSection[];
  faq: { q: string; a: string }[];
  takeaway: string[];
};

/** Легкий запис для списків і тизерів — без тіла статті. */
export type BlogTeaserItem = Pick<BlogArticle,
  'slug' | 'title' | 'description' | 'keywords' | 'category' | 'pages' | 'published' | 'readMin'>;

