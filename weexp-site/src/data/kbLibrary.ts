/**
 * БІБЛІОТЕКА АГЕНЦІЇ — не плутати з «Базою знань клієнта».
 *
 * «База знань» у картці клієнта — це досьє: усе, що ми знаємо про КОНКРЕТНОГО
 * клієнта, зібране з його кабінету, наших нотаток і прогонів рушія. Вона
 * заповнюється сама й нічого не «формує».
 *
 * Бібліотека — навпаки: наші власні матеріали, однакові для всіх клієнтів.
 * Методики, шаблони, чек-листи, інструкції. Їх пише команда, і саме вони
 * відповідають на питання «а як ми це робимо».
 *
 * Два шари, і обидва потрібні:
 *
 *   base — цей файл. Живе в репозиторії, змінюється через рев'ю, є завжди й не
 *          залежить від бази даних. Тут те, що вже зашите в продукт: модель
 *          витоку, каталог доступів, матриця зрілості, структура пакета.
 *   team — таблиця `kb_library` у Supabase (docs/kb-library.sql). Те, що команда
 *          додає з адмінки на ходу. Якщо таблиці ще немає, панель каже про це
 *          прямо — і показує базовий шар, а не порожній екран.
 *
 * Привʼязка до аудиту — через вісім систем (`SysKey`): та сама вісь, якою
 * міряє експрес-аудит і за якою побудований глибокий. Тому в картці клієнта
 * можна показати «ось наші методики під ті системи, де у нього провал».
 */

