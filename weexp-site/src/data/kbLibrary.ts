/** Пошук по обох шарах: назва, опис, текст, система. */
export const kbMatches = (i: KbItem, q: string): boolean => {
  const s = q.trim().toLowerCase();
  if (!s) return true;
  return [i.title, i.summary, i.body, i.url, ...(i.sys || [])].filter(Boolean).join(' ').toLowerCase().includes(s);
};
