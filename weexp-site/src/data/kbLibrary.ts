export type KbItem = {
  id: string;
  title: string;
  kind: KbKind;
  /** До яких із восьми систем належить. Порожньо = загальне. */
  sys: SysKey[];
  /** Одне-два речення: що це і коли брати. Видно у списку. */
  summary: string;
  /** Повний текст. Простий формат: рядки, «— » для пунктів. Без залежностей. */
  body?: string;
  /** Якщо матеріал живе зовні (Drive, Notion) — посилання замість тексту. */
  url?: string;
  /** Чи можна віддавати клієнту. За замовчуванням — ні: це внутрішня кухня. */
  forClient?: boolean;
  by?: string;
  at?: string;
  updatedAt?: string;
  /** Звідки запис: базовий шар у коді чи доданий командою. */
  source: 'base' | 'team';
};

