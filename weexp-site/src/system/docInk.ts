/**
 * Палитра печатаемых документов (экспорт в PDF из кабинета и админки).
 *
 * Эти документы собираются строками HTML со своим инлайновым CSS и не видят
 * токенов сайта — поэтому правило приходится повторить здесь, а не ссылаться
 * на него. Правило то же, что в system.css: фирменный красный `#F5301C` живёт
 * в заливках и крупных начертаниях, а как только он касается текста, берётся
 * `INK.red` — тот же оттенок, доведённый до порога читаемости.
 *
 * Замер (WCAG 2.1, контраст к фону; порог для обычного текста 4.5):
 *   #F5301C  на белом 3.95 · на бумаге #FBF4E4 3.60   — провал в роли текста
 *   #D0230E  на белом 5.35 · на бумаге         4.88   — проходит
 *   #C58A00  на белом 3.00                            — провал в роли текста
 *   #956800  на белом 4.93 · на бумаге         4.50   — проходит
 * Белый текст на заливке:
 *   на #F5301C 3.95 — провал; на #D0230E 5.35 — проходит.
 * Поэтому кнопка с белой подписью тоже берёт INK.red, а не BRAND.red.
 */

/** Заливки и крупные начертания (логотип ≥18.66px bold, полосы, плашки без текста). */
export const BRAND = {
  red: '#F5301C',
  paper: '#FBF4E4',
  rule: '#E3D9C0',
  track: '#EEE7D6',
} as const;

/** Чернила: всё, что является ТЕКСТОМ обычного размера или фоном под белым текстом. */
export const INK = {
  red: '#D0230E',
  amber: '#956800',
  green: '#1F6E4E',
  muted: '#6B675E',
  body: '#1A1714',
} as const;

/** Цвет числа/подписи по баллу здоровья (0–100). Только для текста. */
export const scoreInk = (score: number): string =>
  score < 45 ? INK.red : score < 65 ? INK.amber : INK.green;

/** Цвет заливки полосы по тому же баллу. Заливка — не текст, порог другой. */
export const scoreFill = (score: number): string =>
  score < 45 ? BRAND.red : score < 65 ? '#C58A00' : INK.green;
