import { useLocation } from 'react-router-dom';

/**
 * Легка двомовність без залежностей. Мова визначається з URL: /en/* — англійська,
 * решта — українська (типово). SEO-коректно: обидві мови індексуються окремими
 * URL + hreflang. У компонентах: const t = useT(); t('Укр', 'Eng'). Для посилань:
 * const lp = useLp(); <Link to={lp('/proof')}> — додає /en у EN-режимі.
 */
export type Lang = 'uk' | 'en';

export function langOf(pathname: string): Lang {
  return pathname === '/en' || pathname.startsWith('/en/') ? 'en' : 'uk';
}

export function useLang(): Lang {
  return langOf(useLocation().pathname);
}

/**
 * Мікротипографіка: те, що НЕ можна лишати в кінці рядка.
 *
 * 1. Слово з однієї-двох літер («з», «у», «і», «на», «до», in, of, to) —
 *    українська норма забороняє відривати прийменник від його слова, і саме
 *    такі відриви давали найдовші хвости: «продажів з / того самого» замість
 *    «продажів / з того самого».
 * 2. Пробіл перед тире — тире лишається в кінці рядка, а не починає новий.
 * 3. Число і його одиниця («19 млн», «6 ринків») — розрив тут читається як
 *    два різні числа.
 *
 * Живе в t(), бо це єдина точка, крізь яку проходить УВЕСЬ текст інтерфейсу:
 * інакше правило довелося б пам'ятати в кожному новому рядку копірайту.
 * Нерозривний пробіл на екрані невідрізнимий від звичайного, у пошуковій
 * видачі теж; у DOM це U+00A0, тож заміри переносу бачать саме те, що бачить
 * людина.
 */
const NBSP = '\u00A0';
/*
 * Список, а не «будь-яке слово з однієї-двох літер».
 *
 * Різниця не academic: «Ми перебудовуємо» — теж два символи плюс довге слово,
 * але склеїти їх означає зробити нерозривним шматок у шістнадцять знаків, який
 * у вузькій картці вже нікуди не помістити. Правило стосується службових слів
 * — прийменників і сполучників, — а не всього короткого.
 */
const GLUE = new RegExp(
  '(^|[\\s(«"„])((?:у|в|з|і|й|а|о|та|до|на|за|із|зі|по|чи|бо|не|ні|що|як' +
  '|a|an|of|to|in|on|at|is|by|or))\\s+(?=\\S)', 'gi');
export function typo(s: string): string {
  return s
    // 1 — прийменник/сполучник не лишається в кінці рядка
    .replace(GLUE, `$1$2${NBSP}`)
    /*
     * 3 — число з ОДИНИЦЕЮ, а не з будь-яким наступним словом. Перша версія
     * склеювала число з чим завгодно: «$2,900 за проєкт» ставало нерозривним
     * на «900 за», і в тісній комірці рядок уже не мав де перенестись. Тому
     * склеюємо лише коротке слово-одиницю: млн, тис, грн, ₴, %, год.
     */
    .replace(/(\d)\s+(?=[^\s\d]{1,3}(?:[\s.,;:)]|$))/g, `$1${NBSP}`)
    // 2 — тире не починає рядок
    .replace(/\s+([—–])/g, `${NBSP}$1`);
}

/** t('українською', 'in English') — обирає рядок за поточною мовою. */
export function useT() {
  const lang = useLang();
  return (uk: string, en: string) => typo(lang === 'en' ? en : uk);
}

/** Префіксер посилань: у EN-режимі додає /en (зберігаючи якорі та зовнішні URL). */
export function lpFor(lang: Lang) {
  return (to: string) => {
    if (lang !== 'en') return to;
    if (/^(https?:|mailto:|tel:)/.test(to)) return to;
    if (to === '/') return '/en';
    if (to.startsWith('/#')) return '/en' + to.slice(1); // '/en#systems'
    if (to.startsWith('#')) return to;
    return '/en' + to;
  };
}

export function useLp() {
  return lpFor(useLang());
}

/** Прибирає /en-префікс — щоб перемикач мов вів на той самий маршрут іншою мовою. */
export function stripLang(pathname: string): string {
  if (pathname === '/en') return '/';
  if (pathname.startsWith('/en/')) return pathname.slice(3);
  return pathname;
}
