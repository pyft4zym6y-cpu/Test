/**
 * Текстовые мелочи, из-за которых документ выглядит машинным.
 *
 * Живёт отдельным модулем, потому что потребителей больше одного: протокол QA,
 * экспорт в docx и всё, что печатает число рядом с существительным.
 */

/**
 * Склонение существительного при числительном: 1 проверка, 2 проверки,
 * 5 проверок. Отдельно обрабатываются 11–14 — они всегда просят форму «многих»
 * (11 проверок, а не «11 проверка»), и именно на них ошибаются чаще всего.
 */
export function plural(n: number, one: string, few: string, many: string): string {
  const a = Math.abs(n) % 100, b = a % 10;
  if (a > 10 && a < 20) return many;
  if (b > 1 && b < 5) return few;
  if (b === 1) return one;
  return many;
}
