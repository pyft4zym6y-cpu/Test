function curveSvg(w = 720, h = 190) {
  const L = 46, R = 12, T = 16, B = 34;
  const iw = w - L - R, ih = h - T - B;
  const x = (i) => L + (iw * i) / 14;
  const y = (v) => T + ih - (ih * v) / 10;
  const line = (vals) => vals.map((v, i) => `${x(i).toFixed(1)},${y(v).toFixed(1)}`).join(' ');
  return `<svg width="${w}" height="${h}" viewBox="0 0 ${w} ${h}" style="max-width:100%">
    ${[0, 2, 4, 6, 8, 10].map((v) => `<line x1="${L}" y1="${y(v)}" x2="${w - R}" y2="${y(v)}" stroke="#E3E8E6" stroke-width="1"/><text x="${L - 6}" y="${y(v) + 3}" text-anchor="end" font-family="IBM Plex Mono,monospace" font-size="8" fill="#94A0A8">${v}</text>`).join('')}
    <rect x="${x(5.6)}" y="${T}" width="${x(7.4) - x(5.6)}" height="${ih}" fill="#D6362B" opacity=".06"/>
    <rect x="${x(11.6)}" y="${T}" width="${x(12.4) - x(11.6)}" height="${ih}" fill="#D6362B" opacity=".06"/>
    <polyline points="${line(TGT_R)}" fill="none" stroke="#2A6D5C" stroke-width="2.2"/>
    <polyline points="${line(CUR_R)}" fill="none" stroke="#D6362B" stroke-width="2.2" stroke-dasharray="none"/>
    ${CUR_R.map((v, i) => `<circle cx="${x(i)}" cy="${y(v)}" r="2.6" fill="#D6362B"/>`).join('')}
    ${TGT_R.map((v, i) => `<circle cx="${x(i)}" cy="${y(v)}" r="2.6" fill="#2A6D5C"/>`).join('')}
    ${STG_SHORT.map((s, i) => `<text x="${x(i)}" y="${h - 18}" text-anchor="middle" font-family="IBM Plex Mono,monospace" font-size="7" fill="${[6, 7, 12].includes(i) ? '#D6362B' : '#6E7C86'}" font-weight="${[6, 7, 12].includes(i) ? '700' : '400'}">${i + 1}</text><text x="${x(i)}" y="${h - 8}" text-anchor="middle" font-family="IBM Plex Mono,monospace" font-size="6.5" fill="${[6, 7, 12].includes(i) ? '#D6362B' : '#94A0A8'}">${s}</text>`).join('')}
    <text x="${w - R}" y="${T + 8}" text-anchor="end" font-family="IBM Plex Mono,monospace" font-size="8" fill="#2A6D5C" font-weight="700">ціль день 270 · сер. 7.8/10</text>
    <text x="${w - R}" y="${T + 20}" text-anchor="end" font-family="IBM Plex Mono,monospace" font-size="8" fill="#D6362B" font-weight="700">зараз · сер. 4.2/10</text>
  </svg>`;
}

