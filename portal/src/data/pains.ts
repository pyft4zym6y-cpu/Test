export const BASE_SHEETS = ['10', '11', '12'];

export const PAINS_QID = 'PAINS'; // спец-ID в answers: выбранные боли через ' | '

/** Персональный трек: база + домены выбранных болей по частоте упоминания. */
export function trackFor(painIds: string[]): string[] {
  const score: Record<string, number> = {};
  for (const pid of painIds) {
    const p = PAINS.find((x) => x.id === pid);
    p?.sheets.forEach((s, i) => {
      score[s] = (score[s] ?? 0) + (p.sheets.length - i);
    });
  }
  const ranked = Object.entries(score)
    .sort((a, b) => b[1] - a[1])
    .map(([s]) => s);
  return [...BASE_SHEETS, ...ranked.filter((s) => !BASE_SHEETS.includes(s))];
}
